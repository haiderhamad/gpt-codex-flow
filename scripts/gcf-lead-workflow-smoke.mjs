    assert.equal(response.status,200);assert.equal((await response.json()).executionStarted,false);
    assert.equal((await post('/owner/workflow',{...codexBody,project:temp},headers)).status,400);
    assert.equal((await post('/owner/workflow',{...codexBody,model:'abc;whoami'},headers)).status,400);
    assert.equal((await post('/owner/workflow',{...codexBody,effort:'extreme'},headers)).status,400);
