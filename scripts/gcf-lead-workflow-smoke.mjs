  assert.match(configuredCommand.command,/--effort 'high'/);
  assert.ok(!configuredCommand.command.includes('danger-full-access'));
  assert.deepEqual(ownerLeadSnapshot(manifest)[1].codexExecution,{model:null,effort:'auto'});
  assert.throws(()=>saveOwnerCodexExecutionPreferences(manifest,a,'new-model','low',null,'auto'),/changed/);
  assert.equal(saveOwnerCodexExecutionPreferences(manifest,a,null,'auto','test-codex','high').saved,true);
  const codexFile=path.join(path.dirname(manifest),'gcf-codex-execution-preferences.json');
  assert.equal(fs.statSync(codexFile).mode&0o077,0);
  const configBytes=fs.readFileSync(codexFile);
  fs.chmodSync(codexFile,0o644);
  assert.throws(()=>ownerLeadSnapshot(manifest),/Unsafe owner Codex configuration/,'reject world-readable model preferences');
  fs.chmodSync(codexFile,0o600);
  fs.writeFileSync(codexFile,'{"version":1,"projects":{},"unrecognized":true}');
