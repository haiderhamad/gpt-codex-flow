  assert.ok(defaultCommand.command.includes('--run --return-to-inbox'));
  assert.throws(()=>saveOwnerCodexExecutionPreferences(manifest,temp,'test-codex','high',null,'auto'),/not approved/);
  for(const badModel of [';touch /tmp/x','--model','model name','',12])
    assert.throws(()=>saveOwnerCodexExecutionPreferences(manifest,a,badModel,'high',null,'auto'),/Invalid/);
  assert.throws(()=>saveOwnerCodexExecutionPreferences(manifest,a,null,'extreme',null,'auto'),/Unsupported/);
  assert.equal(saveOwnerCodexExecutionPreferences(manifest,a,'test-codex','high',null,'auto').saved,true);
  assert.deepEqual(ownerLeadSnapshot(manifest)[0].codexExecution,{model:'test-codex',effort:'high'});
