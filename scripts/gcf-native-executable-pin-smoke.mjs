import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {pinNativeCodexExecutable,verifyPinnedNativeCodexExecutable} from './gcf-native-executable-pin.mjs';
const root=await fs.mkdtemp(path.join(os.tmpdir(),'gcf-pin-test-'));
const bin=path.join(root,'bin'),file=path.join(bin,'codex'),sentinel=path.join(root,'INVOKED');
const code='#!/bin/sh\ntouch "'+sentinel+'"\n';
try{
 await fs.mkdir(bin);
 await fs.writeFile(file,code,{mode:0o755});
 const pin=await pinNativeCodexExecutable({searchPath:bin});
 assert.equal(pin.candidate,file);
 assert.equal(pin.candidateKind,'file');
 assert.match(pin.sha256,/^[0-9a-f]{64}$/);
 assert.equal(await verifyPinnedNativeCodexExecutable(pin),await fs.realpath(file));
 await assert.rejects(fs.stat(sentinel),{code:'ENOENT'});
 console.log('PASS: stable native executable SHA-256/inode pinned without running binary');
 await fs.writeFile(file,code+'#modified\n');
 await assert.rejects(verifyPinnedNativeCodexExecutable(pin),/changed/);
 await fs.writeFile(file,code);
 const swapped=path.join(root,'swapped');
 await fs.writeFile(swapped,code,{mode:0o755});
 await fs.rename(swapped,file);
 await assert.rejects(verifyPinnedNativeCodexExecutable(pin),/changed/);
 const fresh=await pinNativeCodexExecutable({searchPath:bin});
 await fs.chmod(file,0o644);
 await assert.rejects(verifyPinnedNativeCodexExecutable(fresh));
 await fs.chmod(file,0o755);
 console.log('PASS: content tamper, same-bytes inode swap and non-executable mode refused');
 const a=path.join(root,'a'),b=path.join(root,'b');
 await fs.writeFile(a,code,{mode:0o755});
 await fs.writeFile(b,code+'echo changed\n',{mode:0o755});
 await fs.rm(file);await fs.symlink(a,file);
 const link=await pinNativeCodexExecutable({searchPath:bin});
 assert.equal(link.candidateKind,'symlink');
 assert.equal(await verifyPinnedNativeCodexExecutable(link),await fs.realpath(a));
 await fs.rm(file);await fs.symlink(b,file);
 await assert.rejects(verifyPinnedNativeCodexExecutable(link),/changed/);
 await assert.rejects(pinNativeCodexExecutable({searchPath:path.join(root,'missing')}),/No readable/);
 await assert.rejects(pinNativeCodexExecutable({searchPath:bin,maxBytes:10}),/bounded/);
 await assert.rejects(fs.stat(sentinel),{code:'ENOENT'});
 console.log('PASS: symlink re-target, missing and oversized executable fail closed');
}finally{await fs.rm(root,{recursive:true,force:true});}
