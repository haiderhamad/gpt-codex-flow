import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {initializeNotionMemory,notionMemoryStatus,optionalNotionAgentsBlock,optionalNotionPointerBlock} from '../dist/gcfNotionMemory.js';
import {renderControlCenterPage} from '../dist/gcfControlCenterPage.js';

const root=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'gcf-notion-memory-')));
try {
  const proj=path.join(root,'sample-project');fs.mkdirSync(proj);
  const agents=path.join(proj,'AGENTS.md');fs.writeFileSync(agents,'# My original agent instructions\n');
  assert.equal(notionMemoryStatus(proj).enabled,false);
  assert.equal(notionMemoryStatus(proj).status,'disabled');
  assert.equal(fs.existsSync(path.join(proj,'NOTION_MEMORY.md')),false);
  assert.equal(initializeNotionMemory(proj).state,'created');
  const file=path.join(proj,'NOTION_MEMORY.md');
  const original=fs.readFileSync(file,'utf8');
  assert.match(original,/sample-project — Optional Notion Project Memory/);
  assert.match(original,/local opt-in instruction template/);
  assert.match(original,/First activation on an existing project/);
  assert.match(original,/First active agent session: find or bootstrap the hub/);
  assert.match(original,/Exactly one match: reuse it/i);
  assert.match(original,/project's page creation under that parent/);
  assert.match(original,/A local opt-in marker or Notion connection alone is not remote write approval/);
  assert.match(original,/Human-readable AND AI-readable documentation/);
  assert.match(original,/Mermaid diagram in a Notion code block/);
  assert.match(original,/Existing page cleanup \/ safe archive/);
  assert.match(original,/backup\/archive copy BEFORE changing canonical content/);
  assert.match(original,/No existing project.*overwritten|previous Git history, README, code and AGENTS.md are not replaced/i);
  assert.match(original,/NOTION_SYNC_PENDING/);
  assert.match(original,/Without this optional feature, GCF Handoff, Task Inbox, Task Resume and Transfer Control work exactly as before/);
  assert.match(original,/continue all GCF task, resume and handoff work normally/);
  // Notion is durable knowledge, while the existing GCF task/inbox stack owns live handoffs.
  for(const term of ['shared_project_state','task_resume','task_inbox_list','task_inbox_read','Keep task state in GCF','Consolidate lasting knowledge only','Check existing notes before writing','Superseded'])
    assert.ok(original.includes(term),'Missing durable-memory / handoff separation: '+term);
  assert.match(original,/Routine tests, a mere handoff or a temporary blocker do not alone warrant a Notion update/);
  assert.match(original,/Never duplicate the canonical project page/i);
  assert.equal(notionMemoryStatus(proj).enabled,true);
  assert.equal(initializeNotionMemory(proj).state,'existing');
  assert.equal(fs.readFileSync(file,'utf8'),original);
  assert.equal(fs.readFileSync(agents,'utf8'),'# My original agent instructions\n');
  const block=optionalNotionAgentsBlock();
  assert.match(block,/optional, owner-pasted only/);
  assert.match(block,/NOTION_SYNC_PENDING/);
  assert.match(block,/Handoff, task progress, agent queues and transient TODOs belong in GCF/);
  assert.match(block,/Consolidate only durable decisions/);
  assert.match(block,/update it in place/);
  assert.match(block,/shared_project_state, task_resume/);
  const pointer=optionalNotionPointerBlock();
  assert.match(pointer,/GCF NOTION MEMORY POINTER START/);
  assert.match(pointer,/If the project-root `NOTION_MEMORY.md` exists and is enabled/);
  assert.match(pointer,/next active coding session/);
  assert.match(pointer,/create a canonical project page and needed subpages/);
  assert.match(pointer,/complete Archive copy first/);
  assert.ok(Buffer.byteLength(original,'utf8')<=12_000,'local Notion instructions must fit safe read limit');
  const skill=fs.readFileSync('.agents/skills/gcf-notion-memory/SKILL.md','utf8');
  const layout=fs.readFileSync('.agents/skills/gcf-notion-memory/references/PROJECT_HUB_LAYOUT.md','utf8');
  for(const keyword of ['Write for two audiences','Mermaid','refine carefully','approved parent','Archive'])
    assert.ok(skill.includes(keyword),'missing human-first or safe Notion Skill guard: '+keyword);
  for(const keyword of ['Human first','AI-ready facts','Mermaid','verified','canonical','Archive','no second handoff database'])
    assert.ok(layout.includes(keyword),'missing layout contract: '+keyword);
  assert.match(layout,/```mermaid\nflowchart TD/);
  assert.match(layout,/Never use bulk delete/);
  assert.match(block,/one hub and needed child pages/);
  assert.match(block,/readable for people/);
  assert.ok(pointer.length<block.length/2,'AGENTS pointer must be materially shorter than full instructions');
  assert.match(pointer,/NOTION_SYNC_PENDING/);
  // Owner-pasted AGENTS.md instructions are recognized without creating another file.
  const agentsOnly=path.join(root,'agents-only');fs.mkdirSync(agentsOnly);
  const agentsFile=path.join(agentsOnly,'AGENTS.md');
  const ownerInstructions='# My own engineering conventions\\n\\n'+block+'\\n';
  fs.writeFileSync(agentsFile,ownerInstructions);
  const detected=notionMemoryStatus(agentsOnly);
  assert.equal(detected.enabled,true);
  assert.equal(detected.source,'agents');
  assert.equal(fs.existsSync(path.join(agentsOnly,'NOTION_MEMORY.md')),false);
  assert.deepEqual(initializeNotionMemory(agentsOnly),{state:'existing',path:'AGENTS.md'});
  assert.equal(fs.readFileSync(agentsFile,'utf8'),ownerInstructions);
  const noClosing=path.join(root,'incomplete-block');fs.mkdirSync(noClosing);
  fs.writeFileSync(path.join(noClosing,'AGENTS.md'),block.split('<!-- GCF NOTION MEMORY END -->')[0]);
  assert.equal(notionMemoryStatus(noClosing).enabled,false);
  const page=renderControlCenterPage('');
  assert.match(page,/id="notion-init"/);
  assert.match(page,/id="notion-method"/);
  assert.match(page,/value="file"/);
  assert.match(page,/value="agents"/);
  assert.match(page,/id="notion-agents-preview"/);
  assert.match(page,/data.notionMemory\?\.source==='file'\?data.optionalNotionPointerBlock:data.optionalAgentsBlock/);
  assert.match(page,/const wantsNotionInstructions=/);
  assert.match(page,/Copy Notion AGENTS.md block/);
  assert.match(page,/initializeNotionMemory/);
  const second=path.join(root,'malicious');fs.mkdirSync(second);
  fs.symlinkSync(file,path.join(second,'NOTION_MEMORY.md'));
  assert.equal(notionMemoryStatus(second).status,'invalid');
  assert.throws(()=>initializeNotionMemory(second),/unsafe|invalid/);
  const disabled=path.join(root,'invalid');fs.mkdirSync(disabled);
  fs.writeFileSync(path.join(disabled,'NOTION_MEMORY.md'),'enabled: true\n');
  assert.equal(notionMemoryStatus(disabled).enabled,false);
  console.log('PASS Notion opt-in: explicit marker, project name, idempotent, preserves existing AGENTS, rejects symlinks and invalid content.');
}finally{fs.rmSync(root,{recursive:true,force:true});}
