import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {auditPublicSource} from './gcf-public-source-audit.mjs';
const root=await fs.mkdtemp(path.join(os.tmpdir(),'gcf-public-audit-fixture-'));
try{
 const git=(...args)=>{const x=spawnSync('git',args,{cwd:root,encoding:'utf8',timeout:10000});assert.equal(x.status,0,x.stderr)};
 git('init','-q');
 await fs.mkdir(path.join(root,'src'));
 await fs.writeFile(path.join(root,'src','app.js'),'export const ok = true;\n');
 await fs.writeFile(path.join(root,'README.md'),'# Product\n![image](docs/missing.png)\n');
 await fs.writeFile(path.join(root,'.gitignore'),'.env\n');
 await fs.writeFile(path.join(root,'.env'),'secret nonpublic ignored fixture\n');
 git('add','README.md','src/app.js','.gitignore');
 let result=await auditPublicSource(root);
 assert.equal(result.status,'BLOCKED');
 assert.ok(result.findings.some(x=>x.code==='README_BROKEN_REFERENCE'));
 assert.equal(result.counts.private_paths,0);
 await fs.mkdir(path.join(root,'docs'));
 await fs.writeFile(path.join(root,'docs','missing.png'),'placeholder');
 result=await auditPublicSource(root);
 assert.equal(result.findings.some(x=>x.code==='README_BROKEN_REFERENCE'),false);
 assert.equal(result.findings.some(x=>x.code==='README_NOT_IN_GIT_CANDIDATE'),false);
 await fs.writeFile(path.join(root,'.gitignore'),'.env\ndocs/missing.png\n');
 result=await auditPublicSource(root);
 assert.ok(result.findings.some(x=>x.code==='README_NOT_IN_GIT_CANDIDATE'&&x.path==='docs/missing.png'));
 await fs.writeFile(path.join(root,'.gitignore'),'.env\n');
 await fs.writeFile(path.join(root,'sample.pem'),'-----BEGIN '+ 'RSA PRIVATE KEY-----\nnon-sensitive fixture\n');
 result=await auditPublicSource(root);
 assert.ok(result.findings.some(x=>x.code==='SENSITIVE_PATH'&&x.path==='sample.pem'));
 assert.ok(result.findings.some(x=>x.code==='PRIVATE_KEY_MATERIAL'&&x.path==='sample.pem'));
 await fs.symlink('src/app.js',path.join(root,'linked.js'));
 result=await auditPublicSource(root);
 assert.ok(result.findings.some(x=>x.code==='SYMLINK'&&x.path==='linked.js'));
 assert.equal(result.git_index_changed,false);
 const live=await auditPublicSource();
 assert.ok(live.counts.candidate>0);
 console.log('LIVE PUBLIC SOURCE PREFLIGHT '+JSON.stringify({status:live.status,counts:live.counts,findings:live.findings}));
 console.log('PASS: read-only tracked/untracked public candidate audit, ignored privacy, link, key, binary and symlink guards');
}finally{await fs.rm(root,{recursive:true,force:true})}
